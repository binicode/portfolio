// Generates src/app/orbit-keyframes.css: the hero stack orbit's keyframes.
// Run: npm run orbit:keyframes. Edit poses or timing here, never in the CSS.
//
// Wider screens: four poses on an ellipse (front, left, back, right) with arc
// midpoints, as transforms; depth is a separate scrim opacity per pose, so
// cards stay opaque. Phones: a flat fade-through, one card at a time.
// Every keyframe animates transform or opacity only (compositor-friendly).
import { writeFileSync } from 'node:fs';

const POSE = {
  F: { t: 'translate3d(0, 7cqh, 0) rotateY(0deg)', dim: 0 },
  L: { t: 'translate3d(-31cqw, 0, -420px) rotateY(24deg)', dim: 0.55 },
  B: { t: 'translate3d(0, -12cqh, -760px) rotateY(0deg)', dim: 0.78 },
  R: { t: 'translate3d(31cqw, 0, -420px) rotateY(-24deg)', dim: 0.55 },
};
const MID = {
  FL: { t: 'translate3d(-22cqw, 5cqh, -130px) rotateY(14deg)', dim: 0.28 },
  LB: { t: 'translate3d(-22cqw, -7cqh, -640px) rotateY(14deg)', dim: 0.68 },
  BR: { t: 'translate3d(22cqw, -7cqh, -640px) rotateY(-14deg)', dim: 0.68 },
  RF: { t: 'translate3d(22cqw, 5cqh, -130px) rotateY(-14deg)', dim: 0.28 },
};
// The ring turns front → left → back → right; card i starts CYCLE[(4 - i) % 4].
const CYCLE = ['F', 'L', 'B', 'R'];
const MIDS = ['FL', 'LB', 'BR', 'RF'];
// Four dwells of 16% and three turns of 12% (each turn's midpoint at +6%).
const DWELLS = [
  [0, 16],
  [28, 44],
  [56, 72],
  [84, 100],
];
const EASE_IN = 'cubic-bezier(0.4, 0, 1, 1)';
const EASE_OUT = 'cubic-bezier(0, 0, 0.6, 1)';
const EASE_IN_OUT = 'cubic-bezier(0.45, 0, 0.55, 1)';

const PHONE = {
  active: { t: 'translateY(0) scale(1)', o: 1 },
  upcoming: { t: 'translateY(7cqh) scale(0.94)', o: 0 },
  past: { t: 'translateY(-7cqh) scale(0.94)', o: 0 },
};

function frame(pct, declarations, ease) {
  const lines = [...declarations, ...(ease ? [`animation-timing-function: ${ease};`] : [])];
  return `  ${pct}% {\n${lines.map((line) => `    ${line}`).join('\n')}\n  }`;
}

function keyframes(name, frames) {
  return `@keyframes ${name} {\n${frames.join('\n\n')}\n}\n`;
}

const blocks = [];

// Wider screens: transform track and scrim (dim) track per card.
for (let i = 0; i < 4; i++) {
  const start = (4 - i) % 4;
  const moves = [];
  const dims = [];
  for (let s = 0; s < 4; s++) {
    const k = (start + s) % 4;
    const pose = POSE[CYCLE[k]];
    const [a, b] = DWELLS[s];
    const last = s === 3;
    moves.push(frame(a, [`transform: ${pose.t};`]));
    moves.push(frame(b, [`transform: ${pose.t};`], last ? undefined : EASE_IN));
    dims.push(frame(a, [`opacity: ${pose.dim};`]));
    dims.push(frame(b, [`opacity: ${pose.dim};`], last ? undefined : EASE_IN));
    if (!last) {
      const mid = MID[MIDS[k]];
      moves.push(frame(b + 6, [`transform: ${mid.t};`], EASE_OUT));
      dims.push(frame(b + 6, [`opacity: ${mid.dim};`], EASE_OUT));
    }
  }
  blocks.push(keyframes(`orbit-${i + 1}`, moves), keyframes(`orbit-dim-${i + 1}`, dims));
}

// Phones: fade through. The outgoing card is gone by the turn's midpoint and
// the incoming one starts only then, so two cards never overlap.
for (let i = 0; i < 4; i++) {
  const frames = [];
  for (let s = 0; s < 4; s++) {
    const pose = i === s ? PHONE.active : i > s ? PHONE.upcoming : PHONE.past;
    const [a, b] = DWELLS[s];
    const last = s === 3;
    const decl = (p) => [`transform: ${p.t};`, `opacity: ${p.o};`];
    frames.push(frame(a, decl(pose)));
    frames.push(frame(b, decl(pose), last ? undefined : EASE_IN));
    if (!last) frames.push(frame(b + 6, decl(i <= s ? PHONE.past : PHONE.upcoming), EASE_OUT));
  }
  blocks.push(keyframes(`orbit-m-${i + 1}`, frames));
}

// Legend: the accent bar steps across the four columns with the dwells.
const legend = DWELLS.flatMap(([a, b], s) => [
  frame(a, [`transform: translateX(${s * 100}%);`]),
  frame(b, [`transform: translateX(${s * 100}%);`], s === 3 ? undefined : EASE_IN_OUT),
]);
blocks.push(keyframes('legend-move', legend));

const header =
  '/* Generated by scripts/gen-orbit-keyframes.mjs (npm run orbit:keyframes).\n' +
  '   Do not edit by hand: change the pose table in the script and re-run. */\n\n';

writeFileSync(new URL('../src/app/orbit-keyframes.css', import.meta.url), header + blocks.join('\n'));
console.log('wrote src/app/orbit-keyframes.css');
